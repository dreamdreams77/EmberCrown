#!/usr/bin/env python3
"""Ember art for the other houses: the same painters as Ashfall Keep with each house's palette.
For every house this writes tiles_<house>.png (floors, wall faces, wall tops) and, for houses with a watch,
pell_<house>.png and gaunt_<house>.png (the two guard silhouettes in the house's colours; their faces reuse
faces_pell/faces_gaunt). Metadata goes to assets/ember/meta_houses.js, which extends EMBER_META.
Usage: python3 tools/ember_art/houses.py [outdir]"""
import os, sys, json, tempfile
sys.path.insert(0, os.path.dirname(__file__))
from pix import ramp, hexc
import build_ember, guards, tiles_ashfall
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'assets', 'ember')
os.makedirs(OUT, exist_ok=True); build_ember.OUT = OUT

# (base, shadow, light) for: floor stone, darker slab, mortar, wall, darker wall, banner cloth, banner trim; guards' two coats and trim
HOUSES = {
  'grell':   dict(st=('#8a6a50', '#2a1410', '#f0cfa0'), std=('#765840', '#22100c', '#d8b488'), mort='#3a2218',
                  wall=('#7a3a30', '#1a0808', '#e8a080'), walld=('#5e2a24', '#140606', '#c88068'), ban=('#9a2a2a', '#300a10', '#f0a080'), trim=('#d9a441', '#5a2a22', '#fff0a0'),
                  coat=('#9a2a2a', '#300a10', '#f0a080'), coat2=('#7a4a1a', '#2a1006', '#e8b870')),
  'sable':   dict(st=('#5a6070', '#141824', '#c0c8dc'), std=('#4a5060', '#10141e', '#a8b0c8'), mort='#1e2230',
                  wall=('#3a4256', '#080a14', '#98a4c0'), walld=('#2e3446', '#06080e', '#808cac'), ban=('#2a2a34', '#0a0a10', '#8a8aa0'), trim=('#c8c8d8', '#3a3a50', '#ffffff'),
                  coat=('#2c2c38', '#0a0a12', '#8888a0'), coat2=('#3e3a48', '#10101a', '#a098b0')),
  'kest':    dict(st=('#6a5048', '#1e1210', '#d0a088'), std=('#5a423a', '#180e0c', '#b88a74'), mort='#2a1814',
                  wall=('#5a3a30', '#120806', '#c08870'), walld=('#46302a', '#0e0604', '#a07060'), ban=('#7a2a18', '#260806', '#f09060'), trim=('#9aa0b4', '#2a2c50', '#ffffff'),
                  coat=('#5a5e6e', '#16182a', '#c0c4d8'), coat2=('#7a4a30', '#240e08', '#e0a070')),
  'dunmoor': dict(st=('#8a90a8', '#262a40', '#eef0ff'), std=('#767c96', '#1e2236', '#d4d8f0'), mort='#30344a',
                  wall=('#3a4a7a', '#0c1024', '#a8b8e8'), walld=('#2e3c66', '#080c1c', '#90a0d0'), ban=('#3a5a96', '#0e1a36', '#b0c8ff'), trim=('#e8eeff', '#5a6080', '#ffffff'),
                  coat=('#2a3a6a', '#0a1028', '#90a8e0'), coat2=('#5a3a6a', '#1a0e24', '#d0a0e0')),
  'hallow':  dict(st=('#7a5a40', '#22140c', '#e8c098'), std=('#684c36', '#1c100a', '#d0a880'), mort='#2e1e14',
                  wall=('#5a4030', '#140a06', '#c89870'), walld=('#48321e', '#100804', '#b08058'), ban=('#c8b898', '#4a3a28', '#fff6e0'), trim=('#ffb040', '#6a3010', '#fff0c0'),
                  coat=('#c8b898', '#4a3a28', '#fff6e0'), coat2=('#3a2a20', '#100806', '#a08870')),
  'hub':     dict(st=('#7a6050', '#22160e', '#e8c8a8'), std=('#685042', '#1c120a', '#d0b090'), mort='#2e2016',
                  wall=('#5a4a44', '#140e0c', '#c8b0a0'), walld=('#4a3c36', '#100a08', '#b09888'), ban=('#7a3a2a', '#28100a', '#f0a080'), trim=('#d9a441', '#5a2a22', '#fff0a0'),
                  coat=None, coat2=None),
}
R = lambda t: ramp(*t)
meta = {}
base_tiles = {k: getattr(tiles_ashfall, k) for k in ('ST', 'STD', 'MORT', 'MORT2', 'WALL', 'WALLD', 'PLUM', 'BONE')}
for h, p in HOUSES.items():
    tiles_ashfall.ST = R(p['st']); tiles_ashfall.STD = R(p['std'])
    tiles_ashfall.MORT = hexc(p['mort']); tiles_ashfall.MORT2 = hexc(p['mort'])
    tiles_ashfall.WALL = R(p['wall']); tiles_ashfall.WALLD = R(p['walld'])
    tiles_ashfall.PLUM = R(p['ban']); tiles_ashfall.BONE = R(p['trim'])
    tmp = tempfile.mkdtemp()                       # never overwrite Ashfall's own tiles.png
    m = tiles_ashfall.build(tmp)
    os.replace(os.path.join(tmp, 'tiles.png'), os.path.join(OUT, 'tiles_' + h + '.png'))
    meta['tiles_' + h] = m['tiles']
    if p['coat']:
        guards.BONE = R(p['trim'])
        for who, cfg, fst, key in (('pell', guards.CFG_A, guards.FACE_A, 'coat'), ('gaunt', guards.CFG_B, guards.FACE_B, 'coat2')):
            c = dict(cfg, coat=R(p[key]), sleeve=R(p[key]))
            name = who + '_' + h
            meta[name] = build_ember.build_person(name, c, fst)
            fp = os.path.join(OUT, 'faces_' + name + '.png')
            if os.path.exists(fp): os.remove(fp)   # faces are shared with Ashfall's pell and gaunt
    print('built', h)
for k, v in base_tiles.items(): setattr(tiles_ashfall, k, v)
open(os.path.join(OUT, 'meta_houses.js'), 'w').write('/* generated by tools/ember_art/houses.py: do not edit */\nObject.assign(EMBER_META,' + json.dumps(meta, separators=(',', ':')) + ');\n')
print('meta', sorted(meta))
