#!/usr/bin/env python3
"""Builds the Ember sheets for the rest of the foes and the bosses (assets/ember/foe_<kind>.png, boss_<kind>.png)
and assets/ember/meta_foes.js, which extends EMBER_META. Layout: one row per (anim, view), frames left to right,
views down, up, left (right is drawn by mirroring the left view). Usage: python3 tools/ember_art/build_foes.py [outdir]"""
import os, sys, json
sys.path.insert(0, os.path.dirname(__file__))
from PIL import Image
import foes2
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'assets', 'ember')
os.makedirs(OUT, exist_ok=True)
VIEWS = ('down', 'up', 'left')
SPECS = {
  'foe_wisp':    (foes2.wisp,    foes2.WW,  foes2.WH,  foes2.WFOOT,  [('hover', 4), ('charge', 1), ('hurt', 1), ('dead', 3)]),
  'foe_husk':    (foes2.husk,    foes2.HW,  foes2.HH,  foes2.HFOOT,  [('walk', 4), ('wind', 1), ('recover', 1), ('hurt', 1), ('dead', 3)]),
  'foe_mite':    (foes2.mite,    foes2.MW,  foes2.MH,  foes2.MFOOT,  [('walk', 4), ('fuse', 2), ('hurt', 1), ('dead', 3)]),
  'foe_warder':  (foes2.chanter, foes2.CWD, foes2.CHT, foes2.CFT,    [('walk', 4), ('cast', 1), ('hurt', 1), ('dead', 3)]),
  'foe_cantor':  (foes2.cantor,  foes2.KW,  foes2.KH,  foes2.KFOOT,  [('walk', 4), ('sing', 1), ('recover', 1), ('hurt', 1), ('dead', 3)]),
  'boss_warden': (foes2.warden,  foes2.BWW, foes2.BWH, foes2.BWFOOT, [('walk', 4), ('wind', 1), ('charge', 4), ('toll', 1), ('stagger', 1), ('dead', 3)]),
  'boss_candle': (foes2.candlemaker, foes2.CMW, foes2.CMH, foes2.CMFOOT, [('float', 4), ('cast', 2), ('slash', 1), ('stagger', 1), ('dead', 3)]),
}
meta = {}
for name, (fn, w, h, foot, anims) in SPECS.items():
    cols = max(n for _, n in anims)
    sh = Image.new('RGBA', (cols * w, len(anims) * 3 * h), (0, 0, 0, 0))
    for ai, (an, n) in enumerate(anims):
        for vi, v in enumerate(VIEWS):
            for f in range(n): sh.alpha_composite(fn(v, an, f).img(), (f * w, (ai * 3 + vi) * h))
    sh.save(os.path.join(OUT, name + '.png'), optimize=True)
    meta[name] = dict(fw=w, fh=h, foot=foot, cols=cols, anims=[a for a, _ in anims], counts={a: n for a, n in anims})
open(os.path.join(OUT, 'meta_foes.js'), 'w').write('/* generated by tools/ember_art/build_foes.py: do not edit */\nObject.assign(EMBER_META,' + json.dumps(meta, separators=(',', ':')) + ');\n')
print('built', sorted(meta))
